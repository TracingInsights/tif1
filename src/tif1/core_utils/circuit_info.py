"""Build :class:`~tif1.models.CircuitInfo` from ``corners.json`` and MultiViewer.

The CDN's ``corners.json`` comes in two shapes, both dict-of-lists:

* old schema: ``CornerNumber, X, Y, Angle, Distance`` plus the scalar
  ``Rotation`` (2021-2024 seasons);
* new schema: the old keys plus ``CornerLetter``, the ``MarshalLight*`` and
  ``MarshalSector*`` marker lists, the ``Section*`` lists, the track outline
  (``TrackX``/``TrackY``/``TrackTime``), ``MiniSectorIndex`` and the circuit
  metadata (``CircuitKey``, ``CircuitName``, ``PitLoss*`` ...).

Missing values may be JSON ``null`` or the string ``"None"``.

When the file is missing, old-schema, or new-schema without corners or
marshal lights, :func:`build_circuit_info` asks the MultiViewer API (the
source fastf1 reads) for the layout once: corners and rotation from the file
win when present, MultiViewer fills the marshal frames, the corner letters
and the extras. The MultiViewer backup never raises.

Frames are built natively for either backend: pandas (``float64``/``int64``/
``object``) or polars (``Float64``/``Int64``/``String``), no round trip.
"""

