def _fill_letters(target: _Markers, donor: _Markers) -> None:
    """Copy corner letters by corner number when ``target`` has none."""
    if any(target.letter) or not any(donor.letter):
        return
    if target.number == donor.number:
        target.letter = list(donor.letter)
        return
    by_number: dict[int, str] = {}
    ambiguous: set[int] = set()
    for number, letter in zip(donor.number, donor.letter, strict=True):
        if number in by_number:
            ambiguous.add(number)
        else:
            by_number[number] = letter
    target.letter = [
        "" if number in ambiguous else by_number.get(number, "") for number in target.number
    ]


def _default_multiviewer_fetch(year: int, circuit_key: int) -> Mapping[str, Any] | None:
    from tif1.mvapi.api import get_circuit

    return get_circuit(year=year, circuit_key=circuit_key)


def _fetch_multiviewer(
    mv_fetch: MultiViewerFetch | None, year: int, circuit_key: int
) -> Mapping[str, Any] | None:
    """One MultiViewer request; any failure is logged and yields ``None``."""
    fetch = mv_fetch if mv_fetch is not None else _default_multiviewer_fetch
    try:
        data = fetch(year, circuit_key)
    except Exception as exc:  # the backup must never raise
        logger.info("MultiViewer circuit %s/%s unavailable: %s", circuit_key, year, exc)
        return None
    if not isinstance(data, Mapping) or not data:
        return None
    return data


def _merge_multiviewer(file: _Parsed, mv: _Parsed) -> None:
    """``corners.json`` wins where it has data; MultiViewer fills the rest."""
    if len(file.corners):
        _fill_letters(file.corners, mv.corners)
    else:
        # No corners in the file: MultiViewer's layout (and its rotation) is used whole.
        file.corners = mv.corners
        file.rotation = mv.rotation
    if file.rotation is None:
        file.rotation = mv.rotation
    if not len(file.marshal_lights):
        file.marshal_lights = mv.marshal_lights
    if not len(file.marshal_sectors):
        file.marshal_sectors = mv.marshal_sectors
    file.extras.fill_from(mv.extras)


def build_circuit_info(
    corners_payload: Mapping[str, Any] | None,
    *,
    year: int,
    circuit_id: str | None,
    circuit_name: str = "",
    country: str = "",
    location: str = "",
    lib: str = "pandas",
    allow_multiviewer: bool = True,
    mv_fetch: MultiViewerFetch | None = None,
) -> CircuitInfo:
    """Build a :class:`CircuitInfo` from ``corners.json`` with the MultiViewer backup.

    Args:
        corners_payload: The session's ``corners.json`` (old or new schema) or
            ``None`` when the CDN has none.
        year: Season of the session (the MultiViewer layout year).
        circuit_id: Ergast ``CircuitId`` of the event (vendored key lookup).
        circuit_name: Ergast ``CircuitName`` (live index match, Mugello remap).
        country: Ergast ``Country`` (live index match).
        location: Ergast ``Location`` (live index match).
        lib: ``"pandas"`` or ``"polars"`` frames.
        allow_multiviewer: Ask MultiViewer when the file is missing, old-schema
            or new-schema without corners or marshal lights.
        mv_fetch: ``(year, circuit_key) -> payload | None`` (default:
            :func:`tif1.mvapi.get_circuit`, cached permanently).

    Returns:
        The circuit info; ``source`` is ``"corners.json"``, ``"multiviewer"``,
        both joined by ``+``, or ``""`` when neither answered.
    """
    sources: list[str] = []
    payload = corners_payload if isinstance(corners_payload, Mapping) and corners_payload else None
    parsed = _parse_corners_payload(payload) if payload is not None else _Parsed()
    if payload is not None:
        sources.append("corners.json")

    needs_backup = (
        payload is None
        or not is_new_schema(payload)
        or not len(parsed.corners)
        or not len(parsed.marshal_lights)
    )
    if allow_multiviewer and needs_backup:
        name = parsed.extras.circuit_name or circuit_name
        circuit_key = parsed.extras.circuit_key
        if circuit_key is None:
            circuit_key = resolve_circuit_key(
                circuit_id,
                circuit_name=circuit_name,
                country=country,
                location=location,
                year=year,
            )
        if circuit_key is None:
            logger.info(
                "No MultiViewer circuit key for %s (%s, %s); marshal data unavailable",
                circuit_id,
                circuit_name,
                year,
            )
        else:
            data = _fetch_multiviewer(mv_fetch, year, multiviewer_request_key(circuit_key, name))
            if data is not None:
                _merge_multiviewer(parsed, _parse_multiviewer_payload(data))
                sources.append("multiviewer")

    return _assemble(parsed, source="+".join(sources), lib=lib)


