# -- scalar coercion ----------------------------------------------------------


def _is_missing(raw: Any) -> bool:
    return raw is None or (isinstance(raw, str) and raw.strip().casefold() in _MISSING_STRINGS)


def _to_float(raw: Any) -> float | None:
    """``None`` for missing/unparsable values (pandas NaN, polars null)."""
    if _is_missing(raw):
        return None
    try:
        value = float(raw)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(value) else value


def _to_float_or_zero(raw: Any) -> float:
    value = _to_float(raw)
    return 0.0 if value is None else value


def _to_int(raw: Any) -> int:
    """``0`` for missing/unparsable values (fastf1's ``int(entry.get("number", 0))``)."""
    value = _to_int_or_none(raw)
    return 0 if value is None else value


def _to_int_or_none(raw: Any) -> int | None:
    if _is_missing(raw) or isinstance(raw, bool):
        return None
    try:
        return int(raw)
    except (TypeError, ValueError):
        try:
            return int(float(raw))
        except (TypeError, ValueError, OverflowError):
            return None


def _to_str(raw: Any) -> str:
    return "" if _is_missing(raw) else str(raw)


def _as_list(raw: Any) -> list[Any]:
    if isinstance(raw, list):
        return raw
    if isinstance(raw, tuple):
        return list(raw)
    return []


# -- columnar intermediates ---------------------------------------------------


@dataclass(slots=True)
class _Markers:
    """Columns of one marker frame before the backend frame is built."""

    x: list[float | None] = field(default_factory=list)
    y: list[float | None] = field(default_factory=list)
    number: list[int] = field(default_factory=list)
    letter: list[str] = field(default_factory=list)
    angle: list[float | None] = field(default_factory=list)
    distance: list[float | None] = field(default_factory=list)

    def __len__(self) -> int:
        return len(self.number)

    def columns(self) -> dict[str, list[Any]]:
        return {
            "X": self.x,
            "Y": self.y,
            "Number": self.number,
            "Letter": self.letter,
            "Angle": self.angle,
            "Distance": self.distance,
        }


@dataclass(slots=True)
class _Extras:
    """The tif1 extras of :class:`CircuitInfo` before the frames are built."""

    circuit_key: int | None = None
    circuit_name: str = ""
    location: str = ""
    country: str = ""
    country_code: str = ""
    country_key: int | None = None
    pit_loss: dict[str, float] = field(default_factory=dict)
    track: dict[str, list[Any]] = field(default_factory=dict)
    sections: dict[str, list[Any]] = field(default_factory=dict)
    mini_sector_index: list[int] = field(default_factory=list)

    def fill_from(self, other: _Extras) -> None:
        """Take every value of ``other`` that is still empty here."""
        if self.circuit_key is None:
            self.circuit_key = other.circuit_key
        if not self.circuit_name:
            self.circuit_name = other.circuit_name
        if not self.location:
            self.location = other.location
        if not self.country:
            self.country = other.country
        if not self.country_code:
            self.country_code = other.country_code
        if self.country_key is None:
            self.country_key = other.country_key
        if not self.pit_loss:
            self.pit_loss = dict(other.pit_loss)
        if not self.track:
            self.track = other.track
        if not self.sections:
            self.sections = other.sections
        if not self.mini_sector_index:
            self.mini_sector_index = list(other.mini_sector_index)


@dataclass(slots=True)
class _Parsed:
    """One source's contribution (``corners.json`` or MultiViewer)."""

    corners: _Markers = field(default_factory=_Markers)
    marshal_lights: _Markers = field(default_factory=_Markers)
    marshal_sectors: _Markers = field(default_factory=_Markers)
    rotation: float | None = None
    extras: _Extras = field(default_factory=_Extras)


# -- corners.json parsing -----------------------------------------------------


def is_new_schema(payload: Any) -> bool:
    """True for a new-schema ``corners.json`` (carries the ``MarshalLight*`` lists)."""
    return isinstance(payload, Mapping) and "MarshalLightX" in payload


def _column(values: list[Any], count: int, convert: Callable[[Any], Any]) -> list[Any]:
    """``convert`` of the first ``count`` values, padding a short list with missing."""
    if len(values) >= count:
        return [convert(values[i]) for i in range(count)]
    out = [convert(value) for value in values]
    out.extend(convert(None) for _ in range(count - len(values)))
    return out


def _markers_from_lists(
    payload: Mapping[str, Any],
    *,
    number_key: str,
    x_key: str,
    y_key: str,
    angle_key: str,
    distance_key: str,
    letter_key: str | None = None,
) -> _Markers:
    numbers = _as_list(payload.get(number_key))
    count = len(numbers)
    if count == 0:
        return _Markers()
    letters = (
        _column(_as_list(payload.get(letter_key)), count, _to_str)
        if letter_key is not None
        else [""] * count
    )
    return _Markers(
        x=_column(_as_list(payload.get(x_key)), count, _to_float),
        y=_column(_as_list(payload.get(y_key)), count, _to_float),
        number=[_to_int(value) for value in numbers],
        letter=letters,
        angle=_column(_as_list(payload.get(angle_key)), count, _to_float),
        distance=_column(_as_list(payload.get(distance_key)), count, _to_float),
    )


def _marshals_from_payload(payload: Mapping[str, Any], prefix: str) -> _Markers:
    return _markers_from_lists(
        payload,
        number_key=f"{prefix}Number",
        x_key=f"{prefix}X",
        y_key=f"{prefix}Y",
        angle_key=f"{prefix}Angle",
        distance_key=f"{prefix}Distance",
    )


def _track_columns(xs: list[Any], ys: list[Any], times: list[Any]) -> dict[str, list[Any]]:
    count = len(xs)
    if count == 0:
        return {}
    return {
        "X": [_to_float(value) for value in xs],
        "Y": _column(ys, count, _to_float),
        "Time": _column(times, count, _to_float),
    }


def _sections_from_payload(payload: Mapping[str, Any], corners: _Markers) -> dict[str, list[Any]]:
    count = len(corners)
    section_types = _as_list(payload.get("SectionType"))
    if count == 0 or len(section_types) != count:
        return {}
    return {
        "Number": list(corners.number),
        "Section": _column(_as_list(payload.get("Section")), count, _to_str),
        "SectionType": [_to_str(value) for value in section_types],
        "StartPercent": _column(_as_list(payload.get("SectionStartPercent")), count, _to_float),
        "EndPercent": _column(_as_list(payload.get("SectionEndPercent")), count, _to_float),
        "StartDistance": _column(_as_list(payload.get("SectionStartDistance")), count, _to_float),
        "EndDistance": _column(_as_list(payload.get("SectionEndDistance")), count, _to_float),
    }


def _pit_loss(normal: Any, sc: Any, vsc: Any) -> dict[str, float]:
    out: dict[str, float] = {}
    for name, raw in (("normal", normal), ("sc", sc), ("vsc", vsc)):
        value = _to_float(raw)
        if value is not None:
            out[name] = value
    return out


def _mini_sectors(raw: Any) -> list[int]:
    out: list[int] = []
    for value in _as_list(raw):
        index = _to_int_or_none(value)
        if index is not None:
            out.append(index)
    return out


def _parse_corners_payload(payload: Mapping[str, Any]) -> _Parsed:
    corners = _markers_from_lists(
        payload,
        number_key="CornerNumber",
        x_key="X",
        y_key="Y",
        angle_key="Angle",
        distance_key="Distance",
        letter_key="CornerLetter",
    )
    parsed = _Parsed(corners=corners, rotation=_to_float(payload.get("Rotation")))
    if not is_new_schema(payload):
        return parsed
    parsed.marshal_lights = _marshals_from_payload(payload, "MarshalLight")
    parsed.marshal_sectors = _marshals_from_payload(payload, "MarshalSector")
    parsed.extras = _Extras(
        circuit_key=_to_int_or_none(payload.get("CircuitKey")),
        circuit_name=_to_str(payload.get("CircuitName")),
        location=_to_str(payload.get("Location")),
        country=_to_str(payload.get("CountryName")),
        country_code=_to_str(payload.get("CountryIocCode")),
        country_key=_to_int_or_none(payload.get("CountryKey")),
        pit_loss=_pit_loss(
            payload.get("PitLossNormal"), payload.get("PitLossSC"), payload.get("PitLossVSC")
        ),
        track=_track_columns(
            _as_list(payload.get("TrackX")),
            _as_list(payload.get("TrackY")),
            _as_list(payload.get("TrackTime")),
        ),
        sections=_sections_from_payload(payload, corners),
        mini_sector_index=_mini_sectors(payload.get("MiniSectorIndex")),
    )
    return parsed


# -- MultiViewer parsing ------------------------------------------------------


def _markers_from_multiviewer(array: Any) -> _Markers:
    """fastf1's marker rows: ``trackPosition.x/y``, ``number``, ``letter``, ``angle``, NaN."""
    markers = _Markers()
    for entry in _as_list(array):
        if not isinstance(entry, Mapping):
            continue
        position = entry.get("trackPosition")
        if not isinstance(position, Mapping):
            position = {}
        markers.x.append(_to_float_or_zero(position.get("x", 0.0)))
        markers.y.append(_to_float_or_zero(position.get("y", 0.0)))
        markers.number.append(_to_int(entry.get("number", 0)))
        markers.letter.append(_to_str(entry.get("letter", "")))
        markers.angle.append(_to_float_or_zero(entry.get("angle", 0.0)))
        markers.distance.append(None)
    return markers


def _parse_multiviewer_payload(data: Mapping[str, Any]) -> _Parsed:
    pit_loss_raw = data.get("pitLoss")
    if not isinstance(pit_loss_raw, Mapping):
        pit_loss_raw = {}
    return _Parsed(
        corners=_markers_from_multiviewer(data.get("corners")),
        marshal_lights=_markers_from_multiviewer(data.get("marshalLights")),
        marshal_sectors=_markers_from_multiviewer(data.get("marshalSectors")),
        rotation=_to_float_or_zero(data.get("rotation", 0.0)),
        extras=_Extras(
            circuit_key=_to_int_or_none(data.get("circuitKey")),
            circuit_name=_to_str(data.get("circuitName")),
            location=_to_str(data.get("location")),
            country=_to_str(data.get("countryName")),
            country_code=_to_str(data.get("countryIocCode")),
            country_key=_to_int_or_none(data.get("countryKey")),
            pit_loss=_pit_loss(
                pit_loss_raw.get("normal"), pit_loss_raw.get("sc"), pit_loss_raw.get("vsc")
            ),
            track=_track_columns(_as_list(data.get("x")), _as_list(data.get("y")), []),
            sections={},
            mini_sector_index=_mini_sectors(data.get("miniSectorsIndexes")),
        ),
    )


# -- frame construction -------------------------------------------------------


def _resolve_lib(lib: str) -> tuple[str, Any]:
    """``("polars", module)`` when requested and installed, else ``("pandas", None)``."""
    if lib == "polars":
        pl = import_supported_polars()
        if pl is not None:
            return "polars", pl
        logger.debug("polars is not available; building circuit info with pandas")
    return "pandas", None


def _pandas_frame(columns: Mapping[str, list[Any]], schema: Mapping[str, str]) -> Any:
    import numpy as np
    import pandas as pd

    names = list(schema)
    if not columns or not next(iter(columns.values())):
        return pd.DataFrame(columns=names)
    data: dict[str, Any] = {}
    for name, kind in schema.items():
        values = columns[name]
        if kind == "float":
            data[name] = np.array(values, dtype="float64")
        elif kind == "int":
            data[name] = np.array(values, dtype="int64")
        else:
            data[name] = pd.Series(values, dtype=object)
    return pd.DataFrame(data, columns=names)


def _polars_frame(pl: Any, columns: Mapping[str, list[Any]], schema: Mapping[str, str]) -> Any:
    dtypes = {"float": pl.Float64, "int": pl.Int64, "str": pl.String}
    pl_schema = {name: dtypes[kind] for name, kind in schema.items()}
    if not columns:
        return pl.DataFrame(schema=pl_schema)
    return pl.DataFrame({name: columns[name] for name in schema}, schema=pl_schema)


def _frame(
    columns: Mapping[str, list[Any]], schema: Mapping[str, str], backend: str, pl: Any
) -> Any:
    if backend == "polars":
        return _polars_frame(pl, columns, schema)
    return _pandas_frame(columns, schema)


def _assemble(parsed: _Parsed, *, source: str, lib: str) -> CircuitInfo:
    from tif1.models import CircuitInfo

    backend, pl = _resolve_lib(lib)
    extras = parsed.extras
    return CircuitInfo(
        corners=_frame(parsed.corners.columns(), _MARKER_SCHEMA, backend, pl),
        marshal_lights=_frame(parsed.marshal_lights.columns(), _MARKER_SCHEMA, backend, pl),
        marshal_sectors=_frame(parsed.marshal_sectors.columns(), _MARKER_SCHEMA, backend, pl),
        rotation=parsed.rotation if parsed.rotation is not None else 0.0,
        circuit_key=extras.circuit_key,
        circuit_name=extras.circuit_name,
        location=extras.location,
        country=extras.country,
        country_code=extras.country_code,
        country_key=extras.country_key,
        pit_loss=dict(extras.pit_loss),
        track=_frame(extras.track, _TRACK_SCHEMA, backend, pl),
        sections=_frame(extras.sections, _SECTIONS_SCHEMA, backend, pl),
        mini_sector_index=list(extras.mini_sector_index),
        source=source,
    )


def circuit_info_from_multiviewer(data: Mapping[str, Any], *, lib: str = "pandas") -> CircuitInfo:
    """fastf1's ``get_circuit_info`` parsing of a MultiViewer payload plus the tif1 extras.

    Args:
        data: The ``/api/v1/circuits/{circuit_key}/{year}`` response.
        lib: ``"pandas"`` or ``"polars"`` frames.

    Returns:
        A :class:`CircuitInfo` with ``source="multiviewer"``; every marker
        ``Distance`` is missing (NaN/null) until ``add_marker_distance`` fits it.
    """
    return _assemble(_parse_multiviewer_payload(data), source="multiviewer", lib=lib)


# -- circuit-key resolution ---------------------------------------------------

_vendored_circuits: dict[str, dict[str, Any]] | None = None


def load_vendored_circuits() -> dict[str, dict[str, Any]]:
    """The packaged ``mv_circuits.json`` keyed by Ergast ``CircuitId`` (read once)."""
    global _vendored_circuits
    if _vendored_circuits is not None:
        return _vendored_circuits
    table: dict[str, dict[str, Any]] = {}
    try:
        raw = files("tif1").joinpath(VENDORED_CIRCUITS_PATH).read_bytes()
        data = json_loads(raw)
    except (FileNotFoundError, OSError, TypeError, ValueError) as exc:
        logger.debug("No vendored MultiViewer circuit table: %s", exc)
        data = None
    if isinstance(data, dict):
        table = {
            str(key): value
            for key, value in data.items()
            if isinstance(value, dict) and _to_int_or_none(value.get("circuitKey")) is not None
        }
    _vendored_circuits = table
    return table


def _normalize_text(value: Any) -> str:
    """ASCII, casefolded, hyphens and underscores as spaces, single-spaced."""
    text = unicodedata.normalize("NFKD", _to_str(value))
    text = "".join(char for char in text if not unicodedata.combining(char))
    text = text.casefold().replace("-", " ").replace("_", " ").replace("'", "")
    return _WHITESPACE.sub(" ", text).strip()


def _normalize_country(value: Any) -> str:
    text = _normalize_text(value)
    return _COUNTRY_ALIASES.get(text, text)


def _name_tokens(text: str) -> set[str]:
    return {token for token in text.split(" ") if token and token not in _NAME_STOPWORDS}


def _match_score(
    entry_name: str, *, circuit_id: str, circuit_name: str, location: str, country: str
) -> int:
    if not entry_name:
        return 0
    if entry_name in (location, circuit_name):
        return 4
    if circuit_id and entry_name == circuit_id:
        return 3
    if circuit_name and f" {entry_name} " in f" {circuit_name} ":
        return 2
    tokens = _name_tokens(entry_name)
    if tokens & (_name_tokens(circuit_name) | _name_tokens(location)):
        return 1
    if country and entry_name == country:
        return 1
    return 0


def _year_rank(entry: Mapping[str, Any], year: int | None) -> tuple[int, int]:
    """Tie-break: a layout listed for ``year`` first, then the newest layout not after it."""
    years = sorted(_to_int(value) for value in _as_list(entry.get("years")))
    if year is None or not years:
        return (0, 0)
    if year in years:
        return (2, year)
    earlier = [value for value in years if value <= year]
    return (1, earlier[-1]) if earlier else (0, -years[0])


def match_circuit_index(
    index: Mapping[Any, Any],
    *,
    circuit_id: str = "",
    circuit_name: str = "",
    country: str = "",
    location: str = "",
    year: int | None = None,
) -> int | None:
    """The MultiViewer circuit key of ``/api/v1/circuits`` matching a schedule row.

    Entries of another country are skipped when ``country`` is given. The
    best name match wins (MultiViewer names are mostly localities:
    ``"Melbourne"``, ``"Spielberg"``, ``"Sakhir"``); an ambiguous best score
    is broken by ``year`` and otherwise resolves to ``None``.

    Args:
        index: The ``/api/v1/circuits`` payload (circuit key -> entry).
        circuit_id: Ergast ``CircuitId`` (``"red_bull_ring"``).
        circuit_name: Ergast ``CircuitName`` (``"Red Bull Ring"``).
        country: Ergast ``Country`` (``"Austria"``).
        location: Ergast ``Location`` (``"Spielberg"``).
        year: Season, used only to break ties between layouts.

    Returns:
        The circuit key or ``None`` when nothing matches unambiguously.
    """
    want_country = _normalize_country(country)
    wanted = {
        "circuit_id": _normalize_text(circuit_id),
        "circuit_name": _normalize_text(circuit_name),
        "location": _normalize_text(location),
        "country": want_country,
    }
    if not any(wanted.values()):
        return None
    candidates: list[tuple[int, tuple[int, int], int]] = []
    for raw_key, entry in index.items():
        if not isinstance(entry, Mapping):
            continue
        key = _to_int_or_none(entry.get("circuitKey", raw_key))
        if key is None:
            continue
        entry_country = _normalize_country(entry.get("country"))
        if want_country and entry_country and entry_country != want_country:
            continue
        score = _match_score(_normalize_text(entry.get("name")), **wanted)
        if score > 0:
            candidates.append((score, _year_rank(entry, year), key))
    if not candidates:
        return None
    candidates.sort(reverse=True)
    best = candidates[0]
    if len(candidates) > 1 and candidates[1][:2] == best[:2]:
        return None
    return best[2]


def multiviewer_request_key(circuit_key: int, circuit_name: str = "") -> int:
    """The key to request from MultiViewer for an F1 live-timing circuit key.

    Mirrors fastf1: Mugello is 149 in the F1 API but 146 at MultiViewer
    (where 149 is Jeddah), so the pair ``(149, "Mugello")`` is remapped.
    """
    return MULTIVIEWER_REQUEST_KEY_OVERRIDES.get(
        (int(circuit_key), circuit_name.strip().casefold()), int(circuit_key)
    )


def resolve_circuit_key(
    circuit_id: str | None,
    *,
    circuit_name: str = "",
    country: str = "",
    location: str = "",
    year: int | None = None,
    allow_live: bool = True,
    index: Mapping[Any, Any] | None = None,
) -> int | None:
    """The MultiViewer circuit key of a schedule row.

    Order: the vendored ``mv_circuits.json`` by Ergast ``CircuitId`` (no
    request), then the ``/api/v1/circuits`` index matched by name/country
    (``index`` when given, else the cached live index when ``allow_live``).

    Args:
        circuit_id: Ergast ``CircuitId`` (``"bahrain"``); ``None``/empty skips the table.
        circuit_name: Ergast ``CircuitName`` for the index match.
        country: Ergast ``Country`` for the index match.
        location: Ergast ``Location`` (locality) for the index match.
        year: Season, breaks ties between layouts in the index match.
        allow_live: Consult the live index when the table has no entry.
        index: An index payload to match instead of the live one.

    Returns:
        The circuit key or ``None``.
    """
    if circuit_id:
        entry = load_vendored_circuits().get(str(circuit_id))
        if entry is not None:
            return _to_int_or_none(entry.get("circuitKey"))
    if index is None:
        if not allow_live:
            return None
        from tif1.mvapi.api import get_circuits_index

        index = get_circuits_index()
    if not index:
        return None
    return match_circuit_index(
        index,
        circuit_id=circuit_id or "",
        circuit_name=circuit_name,
        country=country,
        location=location,
        year=year,
    )


